func TestGenerateFilesInvalidAnnotatedFieldErrors(t *testing.T) {
	tests := []struct {
		name       string
		file       *descriptorpb.FileDescriptorProto
		fieldPath  []int
		wantSubstr string
	}{
		{
			name:       "non-string",
			file:       newInvalidTypeFile(),
			fieldPath:  []int{0, 0},
			wantSubstr: "annotation requires a string field",
		},
		{
			name:       "repeated",
			file:       newRepeatedFile(),
			fieldPath:  []int{0, 0},
			wantSubstr: "annotation requires a non-repeated string field",
		},
		{
			name:       "map",
			file:       newMapFile(),
			fieldPath:  []int{0, 0},
			wantSubstr: "annotation requires a non-map string field",
		},
		{
			name:       "oneof",
			file:       newOneofFile(),
			fieldPath:  []int{0, 0},
			wantSubstr: "annotation requires a non-oneof string field",
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			gen, err := newTestPluginWithFiles(
				[]string{tt.file.GetName()},
				[]*descriptorpb.FileDescriptorProto{
					tt.file,
				},
			)
			require.NoError(t, err)

			message := gen.Files[0].Messages[tt.fieldPath[0]]
			field := message.Fields[tt.fieldPath[1]]
			proto.SetExtension(message.Desc.Options(), eventv1.E_Event, &eventv1.EventOptions{})
			proto.SetExtension(field.Desc.Options(), eventv1.E_EventId, true)

			err = generateFiles(gen)
			require.Error(t, err)
			assert.Contains(t, err.Error(), tt.wantSubstr)
		})
	}
}

func newTestPluginWithFiles(
	filesToGenerate []string,
	files []*descriptorpb.FileDescriptorProto,
) (*protogen.Plugin, error) {
	return protogen.Options{}.New(&pluginpb.CodeGeneratorRequest{
		FileToGenerate: filesToGenerate,
		ProtoFile:      files,
	})
}

func generatedFileContent(gen *protogen.Plugin, suffix string) string {
	for _, file := range gen.Response().File {
		if strings.HasSuffix(file.GetName(), suffix) {
			return file.GetContent()
		}
	}
	return ""
}

