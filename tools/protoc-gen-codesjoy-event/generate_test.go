func TestGenerateFilesSameFileMultipleMessages(t *testing.T) {
	gen, err := newTestPluginWithFiles([]string{"order.proto"}, []*descriptorpb.FileDescriptorProto{
		newOrderFile(),
	})
	require.NoError(t, err)

	file := gen.Files[0]
	orderCreated := file.Messages[0]
	orderDeleted := file.Messages[1]

	proto.SetExtension(orderCreated.Desc.Options(), eventv1.E_Event, &eventv1.EventOptions{})
	proto.SetExtension(orderCreated.Fields[0].Desc.Options(), eventv1.E_EventId, true)
	proto.SetExtension(orderDeleted.Desc.Options(), eventv1.E_Event, &eventv1.EventOptions{
		EventType: "order.deleted",
	})
	proto.SetExtension(orderDeleted.Fields[0].Desc.Options(), eventv1.E_EventId, true)

	require.NoError(t, generateFiles(gen))

	content := generatedFileContent(gen, "order_codesjoy_event.pb.go")
	require.NotEmpty(t, content)
	assert.Contains(t, content, "(*OrderCreated)(nil)")
	assert.Contains(t, content, "(*OrderDeleted)(nil)")
	assert.Contains(t, content, `return "codesjoy.example.order.v1.OrderCreated"`)
	assert.Contains(t, content, `return "order.deleted"`)
	assert.Contains(t, content, `func OnOrderCreated(`)
	assert.Contains(t, content, `func OnOrderDeleted(`)
}

