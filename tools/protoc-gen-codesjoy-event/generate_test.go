func TestGenerateFilesEnabledMessageUsesFullNameByDefault(t *testing.T) {
	gen, err := newTestPluginWithFiles([]string{"order.proto"}, []*descriptorpb.FileDescriptorProto{
		newOrderFile(),
	})
	require.NoError(t, err)

	file := gen.Files[0]
	proto.SetExtension(file.Messages[0].Desc.Options(), eventv1.E_Event, &eventv1.EventOptions{})
	proto.SetExtension(file.Messages[0].Fields[0].Desc.Options(), eventv1.E_EventId, true)
	proto.SetExtension(file.Messages[0].Fields[1].Desc.Options(), eventv1.E_PartitionKey, true)

	require.NoError(t, generateFiles(gen))

	content := generatedFileContent(gen, "order_codesjoy_event.pb.go")
	require.NotEmpty(t, content)
	assert.Contains(t, content, "// Code generated by protoc-gen-codesjoy-event. DO NOT EDIT.")
	assert.Contains(t, content, "var _ xevent.Event = (*OrderCreated)(nil)")
	assert.Contains(t, content, `func (*OrderCreated) EventType() string {`)
	assert.Contains(t, content, `return "codesjoy.example.order.v1.OrderCreated"`)
	assert.Contains(t, content, "return x.GetId()")
	assert.Contains(t, content, "return x.GetOrderId()")
	assert.Contains(t, content, `func (*OrderCreated) Topic() string {`)
	assert.Contains(t, content, "return proto.Marshal(x)")
	assert.Contains(t, content, "return proto.Unmarshal(data, x)")
	assert.Contains(t, content, `func OnOrderCreated(`)
	assert.Contains(t, content, `handlers ...func(context.Context, *OrderCreated) error`)
	assert.Contains(t, content, `return xevent.ErrInvalidEventBinding`)
	assert.Contains(t, content, `xevent.On[*OrderCreated](d, handler)`)
}

